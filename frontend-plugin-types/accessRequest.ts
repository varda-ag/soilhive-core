// What the requester says about themselves is shown to admins as it is: nothing checks it.
// Text is trimmed, and a required one must not be blank.
export interface PluginAccessRequestInput {
  // Slugs of private, published Datasets: 1 to 50, each once.
  datasets: string[];
  capabilities: PluginAccessRequestCapability[];
  // Why the access is needed. Up to 1000 characters.
  message: string;
  // Up to 200 characters.
  requesterName: string;
  country: PluginCountryCode;
  // Up to 200 characters.
  organisation: string;
  // An http(s) address; a bare domain gets `https://`. Blank is the same as left out.
  organisationWebsite?: string;
}

// 'pending' while any Dataset in it waits for a decision.
export type PluginAccessRequestStatus = 'pending' | 'finished' | 'withdrawn';

export interface PluginAccessRequest {
  id: string;
  status: PluginAccessRequestStatus;
  // ISO 8601 in UTC.
  createdAt: string;
}

// What happened to one Dataset of an Access Request. Only 'pending' still waits for a decision.
export type PluginAccessRequestItemStatus = 'pending' | 'approved' | 'denied' | 'withdrawn';

export interface PluginAccessRequestItem {
  dataset: { slug: string; name: string };
  status: PluginAccessRequestItemStatus;
}

// One of the signed-in user's own Access Requests, with a status for each of its Datasets.
export interface PluginOwnAccessRequest extends PluginAccessRequest {
  items: PluginAccessRequestItem[];
}

// A refused Access Request: the HTTP status (0 when there was no response) and the problem body,
// e.g. a 409 with `pending_request_id` or a 403 with `email_required`.
export interface PluginAccessRequestError {
  status: number;
  body: unknown;
}
